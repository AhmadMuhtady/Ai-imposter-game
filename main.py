import openai
import anthropic
from input_and_validation import user_input
from players import setup_players
from game_logic import add_clue, prepare_player_context, prepare_voting_context, add_vote, resolve_game
from ai_models import generate_clue, generate_vote, InvalidAIResponseError

def run_clue_phase(players, secret_word, on_clue=None):
    clues = []
    for player in players:
        rejected_clues = []
        name = player['name']
        
        for attempt in range(3):
            output = prepare_player_context(player, clues, rejected_clues)
            
            try:
                clue = generate_clue(output)
            except (openai.APIConnectionError, anthropic.APIConnectionError) as e:
                print(f"Connection error or timeout for {name} on attempt {attempt + 1}: {e}")
                continue
            except openai.InternalServerError as e:
                print(f"Temporary server failure (5xx) for {name} on attempt {attempt + 1}: {e}")
                continue
            except (openai.AuthenticationError, anthropic.AuthenticationError) as e:
                raise RuntimeError(f"Authentication failed for {name}. Please verify your API keys.") from e
            except (openai.RateLimitError, anthropic.RateLimitError) as e:
                raise RuntimeError(f"Rate limit reached for {name}. Please check your quota or try again later.") from e
            except openai.BadRequestError as e:
                raise RuntimeError(f"Invalid request or unavailable model for {name}: {e}") from e
            except anthropic.APIStatusError as e:
                if e.status_code and e.status_code >= 500:
                    print(f"Temporary server failure (5xx) for {name} on attempt {attempt + 1}: {e}")
                    continue
                elif e.status_code == 429:
                    raise RuntimeError(f"Rate limit reached for {name}. Please check your quota or try again later.") from e
                elif e.status_code in (400, 404):
                    raise RuntimeError(f"Invalid request or unavailable model for {name}: {e}") from e
                else:
                    raise
            except openai.APIStatusError as e:
                if e.status_code and e.status_code >= 500:
                    print(f"Temporary server failure (5xx) for {name} on attempt {attempt + 1}: {e}")
                    continue
                elif e.status_code == 429:
                    raise RuntimeError(f"Rate limit reached for {name}. Please check your quota or try again later.") from e
                elif e.status_code in (400, 404):
                    raise RuntimeError(f"Invalid request or unavailable model for {name}: {e}") from e
                else:
                    raise
            except InvalidAIResponseError as e:
                print(f"Invalid AI Response Error for {name} on attempt {attempt + 1}: {e}")
                continue
            
            try:
                add_clue(clues, name, clue, secret_word)
                if on_clue is not None:
                    on_clue(clues[-1].copy())
                break
            except ValueError as e:
                rejected_clues.append({'rejected_clue': clue, 'Error': str(e)})
                print(f"Invalid clue generated by {name}: {e}")
        else:
            raise RuntimeError(f"Clue Generation Failed: {name} failed to produce a valid clue after 3 attempts due to persistent server issues, formatting errors, or rule violations.")

    return clues
    
def run_voting_phase(players, clues, secret_word, on_vote=None):
    votes = []
    for player in players:
        name = player['name']
        retry_feedback = ''
        for attempt in range(3):
            output = prepare_voting_context(player, clues, retry_feedback)
            
            try:
                vote = generate_vote(output)
            except (openai.APIConnectionError, anthropic.APIConnectionError) as e:
                print(f"Connection error or timeout for {name} on vote attempt {attempt + 1}: {e}")
                continue
            except openai.InternalServerError as e:
                print(f"Temporary server failure (5xx) for {name} on vote attempt {attempt + 1}: {e}")
                continue
            except (openai.AuthenticationError, anthropic.AuthenticationError) as e:
                raise RuntimeError(f"Authentication failed for {name}. Please verify your API keys.") from e
            except (openai.RateLimitError, anthropic.RateLimitError) as e:
                raise RuntimeError(f"Rate limit reached for {name}. Please check your quota or try again later.") from e
            except openai.BadRequestError as e:
                raise RuntimeError(f"Invalid request or unavailable model for {name}: {e}") from e
            except anthropic.APIStatusError as e:
                if e.status_code and e.status_code >= 500:
                    print(f"Temporary server failure (5xx) for {name} on vote attempt {attempt + 1}: {e}")
                    continue
                elif e.status_code == 429:
                    raise RuntimeError(f"Rate limit reached for {name}. Please check your quota or try again later.") from e
                elif e.status_code in (400, 404):
                    raise RuntimeError(f"Invalid request or unavailable model for {name}: {e}") from e
                else:
                    raise
            except openai.APIStatusError as e:
                if e.status_code and e.status_code >= 500:
                    print(f"Temporary server failure (5xx) for {name} on vote attempt {attempt + 1}: {e}")
                    continue
                elif e.status_code == 429:
                    raise RuntimeError(f"Rate limit reached for {name}. Please check your quota or try again later.") from e
                elif e.status_code in (400, 404):
                    raise RuntimeError(f"Invalid request or unavailable model for {name}: {e}") from e
                else:
                    raise
            except InvalidAIResponseError as e:
                print(f"Invalid AI Response Error for {name} on vote attempt {attempt + 1}: {e}")
                continue

            try:
                add_vote(votes, name, vote, output['candidates'], secret_word)
                if on_vote is not None:
                    on_vote(votes[-1].copy())
                break
            except ValueError as e:
                retry_feedback = f"Your previous vote was rejected: {e}. Choose an eligible candidate and provide a valid one-sentence explanation WITHOUT revealing the secret word."
                print(f"Invalid vote generated by {name}: {e}")
        else:
            raise RuntimeError(f"Voting Failed: {name} failed to produce a valid vote after 3 attempts due to persistent server issues, formatting errors, or rule violations.")
    
    return votes

def run_game(category, secret_word):
    category, secret_word = user_input(category, secret_word)
    players, imposter = setup_players(secret_word, category)
    clues = run_clue_phase(players, secret_word)
    votes = run_voting_phase(players, clues,secret_word)
    results = resolve_game(players, votes, imposter)

    return {
        'category': category,
        'secret_word': secret_word,
        'players': players,
        'clues': clues,
        'votes': votes,
        'imposter': imposter,
        'results': results
    }




if __name__ == '__main__':
    results = run_game('Animals', 'Penguin')
    print(results)